import 'names.dart';
import 'spec.dart';

/// Emits a Dart library of static `IconData` constants for [spec].
///
/// Генерирует Dart-библиотеку static-констант `IconData` для [spec].
String emitIconDataLibrary(IconFontSpec spec) {
  final generatedBy = spec.generatedBy ?? 'atmos_icon_font_gen';
  final buf = StringBuffer()
    ..writeln('// Generated by $generatedBy. Do not edit.')
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln();

  final doc = spec.libraryDoc ??
      'Icon font `${spec.fontFamily}` as static [IconData] constants.';
  for (final line in doc.split('\n')) {
    buf.writeln('/// $line');
  }
  buf
    ..writeln('@staticIconProvider')
    ..writeln('abstract final class ${spec.className} {')
    ..writeln('  /// Font family declared for these icons.')
    ..writeln("  static const String fontFamily = '${spec.fontFamily}';")
    ..writeln();

  if (spec.fontPackage != null) {
    buf
      ..writeln('  /// Package that ships [fontFamily].')
      ..writeln(
        "  static const String fontPackage = '${spec.fontPackage}';",
      )
      ..writeln();
  }

  final seen = <String>{};
  for (final icon in spec.icons) {
    final dartName = iconIdToDartName(icon.name);
    if (!seen.add(dartName)) {
      throw ArgumentError(
        'Duplicate Dart name "$dartName" for icon "${icon.name}".',
      );
    }
    final cp = formatCodePoint(icon.codePoint);
    buf
      ..writeln('  /// `${icon.name}` · $cp')
      ..writeln('  static const IconData $dartName = IconData(')
      ..writeln('    0x${icon.codePoint.toRadixString(16).toUpperCase()},')
      ..writeln('    fontFamily: fontFamily,');
    if (spec.fontPackage != null) {
      buf.writeln('    fontPackage: fontPackage,');
    }
    buf
      ..writeln('  );')
      ..writeln();
  }

  buf.writeln('}');
  return buf.toString();
}
