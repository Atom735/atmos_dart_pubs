import 'dart:typed_data';

import 'package:atmos_ttf/atmos_ttf.dart';

/// One icon in an [IconFontSpec].
///
/// Provide either [contours] (font units) or [svgPath] (SVG user units).
///
/// Одна иконка в [IconFontSpec].
/// Нужны либо [contours] (единицы шрифта), либо [svgPath] (единицы SVG).
class IconGlyphSpec {
  /// Creates an icon glyph spec.
  ///
  /// Создаёт спецификацию глифа иконки.
  IconGlyphSpec({
    required this.name,
    required this.codePoint,
    this.contours,
    this.svgPath,
    this.advanceWidth,
    this.leftSideBearing,
  }) : assert(
          (contours != null) ^ (svgPath != null),
          'Provide exactly one of contours or svgPath',
        );

  /// Icon id used to derive the Dart identifier (`git-pull` → `gitPull`).
  ///
  /// Id иконки для Dart-идентификатора (`git-pull` → `gitPull`).
  final String name;

  /// Unicode code point in the Private Use Area (for example `0xE001`).
  ///
  /// Кодпоинт Unicode в PUA (например `0xE001`).
  final int codePoint;

  /// Ready TrueType contours in font units (Y-up).
  ///
  /// Готовые контуры TrueType в единицах шрифта (Y вверх).
  final List<TtfContour>? contours;

  /// SVG path `d` attribute. Converted with Y flip into font space.
  ///
  /// Атрибут SVG path `d`. Конвертируется с переворотом Y
  /// в пространство шрифта.
  final String? svgPath;

  /// Optional advance width (defaults to [IconFontSpec.unitsPerEm]).
  ///
  /// Опциональная ширина продвижения (по умолчанию [IconFontSpec.unitsPerEm]).
  final int? advanceWidth;

  /// Optional left side bearing (default 0).
  ///
  /// Опциональный left side bearing (по умолчанию 0).
  final int? leftSideBearing;
}

/// Input for `generateIconFont`.
///
/// Вход для `generateIconFont`.
class IconFontSpec {
  /// Creates a font generation spec.
  ///
  /// Создаёт спецификацию генерации шрифта.
  IconFontSpec({
    required this.fontFamily,
    required this.className,
    required this.icons,
    this.fontPackage,
    this.unitsPerEm = 1000,
    this.svgViewBoxHeight,
    this.libraryDoc,
    this.generatedBy,
  });

  /// Font family written into the TTF and `IconData.fontFamily`.
  ///
  /// Семейство шрифта в TTF и в `IconData.fontFamily`.
  final String fontFamily;

  /// Dart class name for generated constants (for example `MyIcons`).
  ///
  /// Имя Dart-класса для констант (например `MyIcons`).
  final String className;

  /// Icons to embed.
  ///
  /// Иконки для встраивания.
  final List<IconGlyphSpec> icons;

  /// Optional pub package name for `IconData.fontPackage`.
  ///
  /// Опциональное имя pub-пакета для `IconData.fontPackage`.
  final String? fontPackage;

  /// Units per em for the built font.
  ///
  /// Units per em собираемого шрифта.
  final int unitsPerEm;

  /// SVG viewBox height used when flipping Y (defaults to [unitsPerEm]).
  ///
  /// Высота SVG viewBox при перевороте Y (по умолчанию [unitsPerEm]).
  final double? svgViewBoxHeight;

  /// Optional library / class doc comment body (English).
  ///
  /// Опциональный текст doc-комментария библиотеки / класса (EN).
  final String? libraryDoc;

  /// Optional "Generated by …" marker in the Dart file header.
  ///
  /// Опциональная метка «Generated by …» в шапке Dart-файла.
  final String? generatedBy;
}

/// Output of `generateIconFont`.
///
/// Результат `generateIconFont`.
class IconFontResult {
  /// Creates a result.
  ///
  /// Создаёт результат.
  IconFontResult({
    required this.ttfBytes,
    required this.dartSource,
    required this.font,
  });

  /// Built TrueType bytes.
  ///
  /// Байты собранного TrueType.
  final Uint8List ttfBytes;

  /// Generated Dart source.
  ///
  /// Сгенерированный Dart-исходник.
  final String dartSource;

  /// Parsed font model (same bytes as [ttfBytes]).
  ///
  /// Модель шрифта (те же байты, что [ttfBytes]).
  final TtfFont font;
}
