import 'bytes_emitter.dart';
import 'names.dart';
import 'spec.dart';

String _escapeComment(String s) =>
    s.replaceAll('*/', '*∕').replaceAll('\n', ' ');

/// Emits one asset `part` source.
///
/// Генерирует исходник одного ассета (`part`).
String emitAssetSource({
  required VgGenSpec spec,
  required VgCompiledAsset asset,
}) {
  final privateName = toPrivateClassName(asset.identifier);
  final base = '${spec.className}Asset';
  final partOf = spec.partOfLibrary ?? '${spec.libraryName}.dart';

  final flutterFields = spec.emitStyle == VgEmitStyle.flutter
      ? '''
  static final \$picture = \$class.getPicture();

  @override
  Picture get picture => \$picture;
'''
      : '';

  return '''
// ignore_for_file: camel_case_types

/// Generated by ${spec.generatedBy}. Do not edit.
/// Source: ${_escapeComment(asset.sourceLabel)}
part of '$partOf';

final class $privateName extends $base {
  const $privateName() : super();

  static final \$vgContainer = VgContainer.fromBytes(\$bytes);
  static const \$class = $privateName();
$flutterFields
  @override
  VgContainer get vgContainer => \$vgContainer;

  static const \$bytes = [
${formatByteList(asset.bytes)}
  ];
}
''';
}

/// Emits the main library that wires parts / statics.
///
/// Генерирует главную библиотеку со static-аксессорами.
String emitLibrarySource({
  required VgGenSpec spec,
  required List<VgCompiledAsset> assets,
}) {
  final parts = StringBuffer();
  final statics = StringBuffer();
  for (final a in assets) {
    parts.writeln("part '${a.identifier}.g.dart';");
    statics.writeln(
      '  static const ${spec.prefix}${a.identifier} = '
      '${toPrivateClassName(a.identifier)}.\$class;',
    );
  }

  if (spec.emitStyle == VgEmitStyle.flutter) {
    return '''
/// Generated by ${spec.generatedBy}. Do not edit.
library ${spec.libraryName};

import 'dart:ui';

import 'package:atmos_vector_graphics_core/atmos_vector_graphics_core.dart';
import 'package:atmos_vector_graphics_flutter/atmos_vector_graphics_flutter.dart';
import 'package:flutter/widgets.dart';

// ### GENERATED_START_PARTS ###
${parts.toString().trimRight()}
// ### GENERATED_END_PARTS ###

/// Holder for generated GVG3 assets.
abstract class ${spec.className}Asset {
  const ${spec.className}Asset();

  /// Embedded vector container.
  VgContainer get vgContainer;

  /// Rasterized [Picture] for frame 0.
  Picture get picture;

  /// Frame 0 size.
  Size get size {
    final frame = vgContainer.frames.first;
    return Size(frame.width, frame.height);
  }

  /// Builds a [Picture] for [frameIndex].
  Picture getPicture({int frameIndex = 0}) {
    final recorder = PictureRecorder();
    final canvas = Canvas(recorder);
    final frame = vgContainer.frames[frameIndex];
    final sz = Size(frame.width, frame.height);
    vgContainer.renderToCanvas(canvas, sz, frameIndex: frameIndex);
    return recorder.endRecording();
  }

  /// Flutter widget for frame 0.
  Widget getWidget() {
    return CustomPaint(
      size: size,
      painter: _${spec.className}Painter(this),
    );
  }
}

/// Public accessors.
abstract final class ${spec.className} {
  // ### GENERATED_START_STATICS ###
${statics.toString().trimRight()}
  // ### GENERATED_END_STATICS ###
}

class _${spec.className}Painter extends CustomPainter {
  const _${spec.className}Painter(this.asset);

  final ${spec.className}Asset asset;

  @override
  void paint(Canvas canvas, Size size) {
    canvas.drawPicture(asset.picture);
  }

  @override
  bool shouldRepaint(covariant _${spec.className}Painter oldDelegate) =>
      oldDelegate.asset != asset;
}
''';
  }

  return '''
/// Generated by ${spec.generatedBy}. Do not edit.
library ${spec.libraryName};

import 'package:atmos_vector_graphics_core/atmos_vector_graphics_core.dart';

// ### GENERATED_START_PARTS ###
${parts.toString().trimRight()}
// ### GENERATED_END_PARTS ###

/// Holder for generated GVG3 assets.
abstract class ${spec.className}Asset {
  const ${spec.className}Asset();

  /// Embedded vector container.
  VgContainer get vgContainer;

  /// Frame 0 width / height.
  ({double width, double height}) get size {
    final frame = vgContainer.frames.first;
    return (width: frame.width, height: frame.height);
  }
}

/// Public accessors.
abstract final class ${spec.className} {
  // ### GENERATED_START_STATICS ###
${statics.toString().trimRight()}
  // ### GENERATED_END_STATICS ###
}
''';
}
